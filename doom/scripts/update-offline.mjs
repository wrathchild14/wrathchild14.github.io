import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
async function filesIn(directory) {
    const entries = await readdir(path.join(root, directory), { withFileTypes: true });
    const groups = await Promise.all(
        entries.map((entry) => {
            const relative = path.posix.join(directory, entry.name);
            return entry.isDirectory() ? filesIn(relative) : [relative];
        }),
    );
    return groups.flat();
}

const assets = [
    'index.html',
    'index.css',
    'install.js',
    'manifest.webmanifest',
    'common/theme.css',
    'common/models/hell.jpeg',
    'lib/gl-matrix-min.js',
    ...(await filesIn('game')),
    ...(await filesIn('icons')),
    ...(await filesIn('common/models/1level')),
].sort();
const hash = createHash('sha256');
for (const file of [...assets, 'sw.js']) {
    hash.update(file);
    hash.update(await readFile(path.join(root, file)));
}
const version = hash.digest('hex').slice(0, 16);
const source = `// Generated by scripts/update-offline.mjs. Do not edit by hand.\nself.OFFLINE_VERSION = '${version}';\nself.OFFLINE_ASSETS = ${JSON.stringify(assets, null, 4)};\n`;
await writeFile(path.join(root, 'offline-assets.js'), source);
console.log(`Offline release ${version}: ${assets.length} assets.`);
